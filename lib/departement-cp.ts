/** Extracts the leading department code from a Parametres-style label like
 * "02 - Aisne" -> "02". */
export function extractDeptCode(label: string): string {
  const m = label.trim().match(/^([0-9]{2}|2A|2B)/i);
  return m ? m[1].toUpperCase() : '';
}

export function referenceCpForDept(deptLabel: string): string | null {
  const code = extractDeptCode(deptLabel);
  return DEPT_REFERENCE_CP[code] || null;
}
